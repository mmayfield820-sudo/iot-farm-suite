import request from './request'

export const getFarmList = (params) => request.get('/farms', { params })
export const getFarm = (farmId) => request.get(`/farms/${farmId}`)
export const createFarm = (data) => request.post('/farms', data)
export const updateFarm = (farmId, data) => request.patch(`/farms/${farmId}`, data)
export const getFarmOverview = (farmId) => request.get(`/farms/${farmId}/overview`)
export const getFarmManagementStatistics = (farmId) => request.get(`/farms/${farmId}/management-statistics`)
export const getPlotList = (params) => request.get('/plots', { params })
export const createPlot = (data) => request.post('/plots', data)
export const updatePlot = (plotId, data) => request.patch(`/plots/${plotId}`, data)
export const getAllDevices = (params) => request.get('/devices', { params })
export const createDevice = (data) => request.post('/devices', data)
export const bindDevice = (deviceId, plotId) => request.post(`/devices/${deviceId}/bind`, { plotId })
export const unbindDevice = (deviceId) => request.delete(`/devices/${deviceId}/bind`)
export const getUserList = (params) => request.get('/users', { params })
export const saveUser = (id, data) => id ? request.patch(`/users/${id}`, data) : request.post('/users', data)
export const updateUserActive = (id, active) => request.patch(`/users/${id}/status`, { status: active ? 'active' : 'disabled' })
export const resetUserPassword = (id) => request.post(`/users/${id}/initial-password/reset`)
export const downloadUserImportTemplate = () => request.get('/users/import-template', { responseType: 'blob' })
export const previewUserImport = (file) => {
  const formData = new FormData()
  formData.append('file', file)
  return request.post('/users/import-jobs', formData)
}
export const commitUserImport = (jobId) => request.post(`/users/import-jobs/${jobId}/commit`)
